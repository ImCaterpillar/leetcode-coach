export function familyOf(tag) {
  if (/滑动窗口|子串|单调队列/.test(tag)) return "滑动窗口";
  if (/双指针|快慢指针/.test(tag)) return "双指针";
  if (/链表/.test(tag)) return "链表";
  if (/二叉树|BST|树形DP/.test(tag)) return "二叉树";
  if (/回溯/.test(tag)) return "回溯";
  if (/DFS|BFS|拓扑|字典树/.test(tag)) return "图 / 搜索";
  if (/二分/.test(tag)) return "二分";
  if (/堆/.test(tag)) return "堆";
  if (/DP|背包/.test(tag)) return "动态规划";
  if (/栈/.test(tag)) return "栈";
  if (/矩阵/.test(tag)) return "矩阵";
  if (/贪心|投票/.test(tag)) return "贪心";
  if (/哈希|前缀和|数组|区间|前后缀|原地/.test(tag)) return "数组 / 哈希";
  return tag;
}

export function finePatternOf(tag) {
  if (/背包/.test(tag)) return "背包 DP";
  if (/树形DP/.test(tag)) return "树形 DP";
  if (/DP\/二分/.test(tag)) return "DP + 二分";
  if (/中心扩展/.test(tag)) return "中心扩展";
  if (/单调栈/.test(tag)) return "单调栈";
  if (/单调队列/.test(tag)) return "单调队列";
  if (/快慢指针/.test(tag)) return "快慢指针";
  if (/前缀和/.test(tag)) return "前缀和";
  if (/二分/.test(tag)) return "二分边界";
  if (/链表\/归并/.test(tag)) return "链表归并";
  return tag.split("/")[0];
}

